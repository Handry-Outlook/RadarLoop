/** Expands a ramp into [value, rgba] level pairs with a transparent first stop. */
export function buildPalette(ramp) {
  return MMH_INTERVALS.map((value, index) => [
    value,
    index === 0 ? [0, 0, 0, 0] : ramp[Math.min(index - 1, ramp.length - 1)].slice(),
  ]);
}

